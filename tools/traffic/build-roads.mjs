// Builds server/nakama/roads.js: Poway's drivable road graph, compact, for the server-run traffic (server/nakama/index.js).
//   node tools/traffic/build-roads.mjs
// From poway-data.js (generated; see its header for sources). Each edge: [a, b, type, width (m, game scale), one-way, mph,
// points as decimetre integers [x0, z0, x1, z1, ...]]. Footways and service tracks (type > 5) are left out.
import { readFileSync, writeFileSync } from 'node:fs';
import { roadFitter } from '../../src/world/roadwidth.js';
const src = readFileSync(new URL('../../poway-data.js', import.meta.url), 'utf8');
const D = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
const ROAD_SCALE = 1.15; // index.html
const out = [], fit = roadFitter(D.buildings); // the same widths index.html draws
for (const e of D.edges) {
  const [a, b, t, w, ow, , pts, mph] = e; if (t > 5) continue;
  out.push([a, b, t, Math.round(fit(t, w * ROAD_SCALE, ow, pts) * 10) / 10, ow ? 1 : 0, mph || 0, pts.map(v => Math.round(v * 10))]); // as wide as index.html draws them
}
const body = `// generated by tools/traffic/build-roads.mjs from poway-data.js (OpenStreetMap contributors, ODbL). Don't edit by hand.\nvar ROADS = ${JSON.stringify({ e: out })};\n`;
writeFileSync(new URL('../../server/nakama/roads.js', import.meta.url), body);
console.log(`${out.length} edges, ${(body.length / 1024).toFixed(0)} KB`);
