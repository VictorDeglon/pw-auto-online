// Copies the shared block of src/games/defs.js (between BEGIN SHARED and END SHARED) into server/nakama/index.js,
// so the game and the server judge the crew-garage games from the same data; then writes src/games/room-module.js,
// the whole server module wrapped for the browser (src/games/localroom.js runs it when the game server isn't there).
//   node tools/sync-game-defs.mjs           write it
//   node tools/sync-game-defs.mjs --check   exit 1 if the server's copy is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src/games/defs.js'), DST = join(root, 'server/nakama/index.js');
const B = '// BEGIN SHARED', E = '// END SHARED';
const block = s => { const a = s.indexOf(B), b = s.indexOf(E); if (a < 0 || b < a) throw new Error('no shared block'); return [a, b + E.length]; };
const src = readFileSync(SRC, 'utf8'), dst = readFileSync(DST, 'utf8');
const [a, b] = block(src), [c, d] = block(dst);
const want = src.slice(a, b), have = dst.slice(c, d);
const ROOM = join(root, 'src/games/room-module.js');
const roomFor = server => `// Generated by tools/sync-game-defs.mjs from server/nakama/index.js: don't edit. src/games/localroom.js runs it in the
// browser when the game server can't be reached, so the crew garages still open (solo, by the same rules).
export default function load() {
${server}
return InitModule;
}
`;
const roomNow = (() => { try { return readFileSync(ROOM, 'utf8'); } catch (e) { return ''; } })();
if (process.argv.includes('--check')) {
  if (want !== have) { console.error('server/nakama/index.js has an old copy of src/games/defs.js: run node tools/sync-game-defs.mjs'); process.exit(1); }
  if (roomNow !== roomFor(dst)) { console.error('src/games/room-module.js is out of date: run node tools/sync-game-defs.mjs'); process.exit(1); }
  console.log('in sync');
} else {
  const server = want === have ? dst : dst.slice(0, c) + want + dst.slice(d);
  if (want !== have) { writeFileSync(DST, server); console.log('copied the shared defs into server/nakama/index.js'); } else console.log('defs already in sync');
  if (roomNow !== roomFor(server)) { writeFileSync(ROOM, roomFor(server)); console.log('wrote src/games/room-module.js'); } else console.log('room module already up to date');
}
